import streamlit as st

from simulation import FAILURE_ACTIONS, HELP_ACTIONS, generate_users

CALLED_LABEL = "Called"
NOT_CALLED_LABEL = "Did not call"
N_EXAMPLES = 5

st.title("🎲 Generate Action Sequences")
st.markdown(
    """
Create synthetic users. Each user gets a label (**called** or **did not call**) and a sequence of
actions from the last two hours. The label decides which transition matrix generates the actions.
"""
)

with st.form("settings"):
    col_users, col_rate, col_seed = st.columns(3)
    n_users = col_users.number_input("Number of users", min_value=100, max_value=20_000,
                                     value=2_000, step=100)
    call_rate = col_rate.slider("Share of users who call", min_value=0.01, max_value=0.50,
                                value=0.05, step=0.01)
    seed = col_seed.number_input("Random seed", min_value=0, max_value=1_000_000, value=1,
                                 help="The same seed always creates the same users.")
    min_actions, max_actions = st.slider("Number of actions per user", min_value=2,
                                         max_value=40, value=(3, 20))
    st.form_submit_button("Generate users", type="primary")


@st.cache_data(show_spinner="Generating users...")
def load_users(n_users, call_rate, min_actions, max_actions, seed):
    users = generate_users(n_users, call_rate, min_actions, max_actions, seed)
    users["label"] = users["called"].map({1: CALLED_LABEL, 0: NOT_CALLED_LABEL})
    return users


users = load_users(int(n_users), float(call_rate), int(min_actions), int(max_actions), int(seed))
callers = users[users["called"] == 1]
non_callers = users[users["called"] == 0]

col_total, col_callers, col_non_callers, col_actual_rate = st.columns(4)
col_total.metric("Users", f"{len(users):,}")
col_callers.metric("Called", f"{len(callers):,}")
col_non_callers.metric("Did not call", f"{len(non_callers):,}")
col_actual_rate.metric("Actual call rate", f"{len(callers) / len(users):.1%}")


def format_sequence(actions):
    parts = []
    for action in actions:
        if action in FAILURE_ACTIONS:
            parts.append(f":red[**{action}**]")
        elif action in HELP_ACTIONS:
            parts.append(f":orange[**{action}**]")
        else:
            parts.append(action)
    return " → ".join(parts)


TABLE_COLUMNS = {
    "user_id": st.column_config.TextColumn("User"),
    "n_actions": st.column_config.NumberColumn("Actions"),
    "actions": st.column_config.ListColumn("Action sequence", width="large"),
    "label": st.column_config.TextColumn("Classification"),
}


def show_group(group, title, description):
    st.subheader(title)
    st.caption(description)
    if group.empty:
        st.info("No users in this group. Try more users or a higher call rate.")
        return
    st.markdown("**Example sequences** — failures in red, help page in orange:")
    for _, user in group.head(N_EXAMPLES).iterrows():
        st.markdown(f"`{user['user_id']}` &nbsp; {format_sequence(user['actions'])}")
    st.markdown(f"**All {len(group):,} sequences:**")
    st.dataframe(group[["user_id", "n_actions", "actions"]], column_config=TABLE_COLUMNS,
                 hide_index=True, width="stretch")


def color_label(label):
    # Semi-transparent background with colored text stays readable in light and dark themes.
    if label == CALLED_LABEL:
        return "background-color: rgba(255, 75, 75, 0.2); color: #ff4b4b; font-weight: bold"
    return "background-color: rgba(33, 195, 84, 0.2); color: #21c354; font-weight: bold"


tab_callers, tab_non_callers, tab_all = st.tabs([
    f"📞 Called ({len(callers):,})",
    f"✅ Did not call ({len(non_callers):,})",
    f"📋 All users ({len(users):,})",
])

with tab_callers:
    show_group(callers, "Users who called",
               "These sequences were generated by the WILL call transition matrix.")

with tab_non_callers:
    show_group(non_callers, "Users who did not call",
               "These sequences were generated by the will NOT call transition matrix.")

with tab_all:
    st.subheader("All users")
    st.caption("Both groups together. The right column is the classification.")
    show_only = st.radio("Show", ["All", CALLED_LABEL, NOT_CALLED_LABEL], horizontal=True)
    table = users if show_only == "All" else users[users["label"] == show_only]
    table = table[["user_id", "n_actions", "actions", "label"]]

    # A narrower sequence column keeps the classification column visible without scrolling.
    all_users_columns = {
        **TABLE_COLUMNS,
        "actions": st.column_config.ListColumn("Action sequence", width="medium"),
    }
    st.dataframe(table.style.map(color_label, subset=["label"]), column_config=all_users_columns,
                 hide_index=True, width="stretch")

    csv = table.assign(actions=table["actions"].map(" ".join)).to_csv(index=False)
    st.download_button("Download as CSV", csv, file_name="user_sequences.csv", mime="text/csv")
